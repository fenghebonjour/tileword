// For ∅ initial: final → canonical written pinyin
const ZERO_MAP: Record<string, string> = {
  a:'a', ai:'ai', ao:'ao', an:'an', ang:'ang',
  e:'e', ei:'ei', en:'en', er:'er',
  o:'o', ou:'ou',
  i:'yi', ia:'ya', iao:'yao', ie:'ye', iu:'you', ian:'yan', in:'yin', iang:'yang', ing:'ying', iong:'yong',
  u:'wu', ua:'wa', uo:'wo', uai:'wai', ui:'wei', uan:'wan', un:'wen', uang:'wang',
  ü:'yu', üe:'yue', üan:'yuan', ün:'yun',
};

// Returns canonical pinyin for (initial, final), or null if invalid
export function getPinyin(initial: string, final: string): string | null {
  const combos = VALID_COMBOS[initial];
  if (!combos || !combos.includes(final)) return null;

  if (initial === '∅') return ZERO_MAP[final] ?? null;

  // j q x + ü-group: ü → u in written form
  if ((initial === 'j' || initial === 'q' || initial === 'x') && final.startsWith('ü')) {
    return initial + final.replace('ü', 'u');
  }
  return initial + final;
}

// Build the full valid syllable set
export const VALID_SYLLABLES = new Set<string>();
for (const init of INITIALS) {
  const combos = VALID_COMBOS[init] ?? [];
  for (const fin of combos) {
    const syl = getPinyin(init, fin);
    if (syl) VALID_SYLLABLES.add(syl);
  }
}

